//! Generates `ms-psi/src/charset_tables.rs` from the upstream C++ header.

use std::error::Error;
use std::fmt::Write as _;

const OUTPUT: &str = "crates/ms-psi/src/charset_tables.rs";
const HEADER: &str = "// Generated by crates/ms-psi/gen-charset from the upstream dvb_charset_tables.h.\n\
// Regenerate: cargo run -p gen-charset -- <path-to-dvb_charset_tables.h>\n\n";

fn main() -> Result<(), Box<dyn Error>> {
    let path = std::env::args()
        .nth(1)
        .ok_or("usage: gen-charset <path-to-dvb_charset_tables.h>")?;
    let source = std::fs::read_to_string(path)?;
    let source = strip_comments(&source);

    // The C++ tables are ragged: missing row entries are implicitly zero.
    let conv = rows(&source, "conv_8859_table", 14, 96)?;
    let single = flat(&source, "iso6937_single_byte", 96)?;
    let lone = flat(&source, "iso6937_lone_accents", 16)?;
    let multi = rows(&source, "iso6937_multi_byte", 16, 52)?;

    let mut out = String::from(HEADER);
    write_table(
        &mut out,
        "CONV_8859_TABLE",
        "[[u16; 96]; 14]",
        &conv,
        14,
        96,
    );
    write_table(&mut out, "ISO6937_SINGLE_BYTE", "[u16; 96]", &single, 1, 96);
    write_table(&mut out, "ISO6937_LONE_ACCENTS", "[u16; 16]", &lone, 1, 16);
    write_table(
        &mut out,
        "ISO6937_MULTI_BYTE",
        "[[u16; 52]; 16]",
        &multi,
        16,
        52,
    );

    // Each table ends with a blank separator line; keep a single final newline for rustfmt.
    std::fs::write(OUTPUT, format!("{}\n", out.trim_end()))?;
    Ok(())
}

fn strip_comments(source: &str) -> String {
    let bytes = source.as_bytes();
    let mut out = String::with_capacity(source.len());
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index] == b'/' && bytes.get(index + 1) == Some(&b'*') {
            index += 2;
            while index + 1 < bytes.len() && !(bytes[index] == b'*' && bytes[index + 1] == b'/') {
                index += 1;
            }
            index = (index + 2).min(bytes.len());
        } else if bytes[index] == b'/' && bytes.get(index + 1) == Some(&b'/') {
            while index < bytes.len() && bytes[index] != b'\n' {
                index += 1;
            }
        } else {
            out.push(bytes[index] as char);
            index += 1;
        }
    }
    out
}

fn initializer_bounds(source: &str, name: &str) -> (usize, usize) {
    let start = source
        .find(name)
        .unwrap_or_else(|| panic!("missing table {name}"));
    let open = start
        + source[start..]
            .find('{')
            .unwrap_or_else(|| panic!("missing initializer for {name}"));
    let bytes = source.as_bytes();
    let mut depth = 0usize;
    let mut index = open;
    while index < bytes.len() {
        match bytes[index] {
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    return (open, index);
                }
            }
            _ => {}
        }
        index += 1;
    }
    panic!("unterminated initializer for {name}");
}

fn hex_at(source: &str, index: usize) -> Option<(u16, usize)> {
    let bytes = source.as_bytes();
    if bytes.get(index) != Some(&b'0') || !matches!(bytes.get(index + 1), Some(&b'x') | Some(&b'X'))
    {
        return None;
    }
    let mut end = index + 2;
    while end < bytes.len() && bytes[end].is_ascii_hexdigit() {
        end += 1;
    }
    let value = u16::from_str_radix(&source[index + 2..end], 16)
        .unwrap_or_else(|_| panic!("invalid hex value at byte {index}"));
    Some((value, end))
}

/// Parses a braced two-dimensional table, zero-filling short rows.
fn rows(source: &str, name: &str, nrows: usize, ncols: usize) -> Result<Vec<u16>, String> {
    let (open, close) = initializer_bounds(source, name);
    let bytes = source.as_bytes();
    let mut result = Vec::new();
    let mut index = open + 1;
    while index < close {
        if bytes[index] != b'{' {
            index += 1;
            continue;
        }
        let mut row = Vec::new();
        index += 1;
        while index < close {
            match bytes[index] {
                b'}' => {
                    index += 1;
                    break;
                }
                b'{' => index += 1,
                _ => match hex_at(source, index) {
                    Some((value, next)) => {
                        row.push(value);
                        index = next;
                    }
                    None => index += 1,
                },
            }
        }
        if row.len() > ncols {
            return Err(format!(
                "{name}: row has {} values, expected {ncols}",
                row.len()
            ));
        }
        row.resize(ncols, 0);
        result.extend(row);
    }
    expect_len(name, &result, nrows * ncols)?;
    Ok(result)
}

/// Parses a one-dimensional table, zero-filling missing entries.
fn flat(source: &str, name: &str, want: usize) -> Result<Vec<u16>, String> {
    let (open, close) = initializer_bounds(source, name);
    let mut values = Vec::new();
    let mut index = open + 1;
    while index < close {
        match hex_at(source, index) {
            Some((value, next)) => {
                values.push(value);
                index = next;
            }
            None => index += 1,
        }
    }
    if values.len() > want {
        return Err(format!(
            "{name}: expected {want} values, found {}",
            values.len()
        ));
    }
    values.resize(want, 0);
    Ok(values)
}

fn expect_len(name: &str, values: &[u16], want: usize) -> Result<(), String> {
    if values.len() == want {
        Ok(())
    } else {
        Err(format!(
            "{name}: expected {want} values, found {}",
            values.len()
        ))
    }
}

fn write_table(out: &mut String, name: &str, ty: &str, values: &[u16], rows: usize, cols: usize) {
    let _ = writeln!(out, "#[rustfmt::skip]");
    let _ = writeln!(out, "pub(crate) const {name}: {ty} = [");
    for row in 0..rows {
        if rows > 1 {
            let _ = writeln!(out, "    [");
        }
        for chunk in values[row * cols..(row + 1) * cols].chunks(12) {
            out.push_str("        ");
            for (index, value) in chunk.iter().enumerate() {
                if index > 0 {
                    out.push_str(", ");
                }
                let _ = write!(out, "0x{value:04X}");
            }
            out.push_str(",\n");
        }
        if rows > 1 {
            let _ = writeln!(out, "    ],");
        }
    }
    let _ = writeln!(out, "];\n");
}
