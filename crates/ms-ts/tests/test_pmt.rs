#[test]
fn test_wait_pusi() {
    let max_len = 3 * 188;
    let mut buf = vec![0u8; max_len];
    for i in (0..max_len).step_by(188) {
        let b = &mut buf[i..i + 188];
        b[0] = 0x47;
        b[1] = 0x00; // no packet start
        b[2] = 0xFF; // pid
        b[3] = 0xC0; // encrypted + parity 1
    }
    // second packet changes parity
    buf[188 + 3] = 0x80;

    // keep the same parity
    buf[2 * 188 + 3] = 0x80;
    buf[2 * 188 + 1] |= 0x40;

    assert!(!wait_pusi(&buf[..188], &[0xFF]), "wait_pusi failed");
    assert!(
        wait_pusi(&buf[..2 * 188], &[0xFF]),
        "getItem should not fail"
    );
    assert!(
        !wait_pusi(&buf[..3 * 188], &[0xFF]),
        "getItem should not fail"
    );
}

