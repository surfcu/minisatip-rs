#[test]
fn test_filter_add_del_mt() {
    const T: usize = 4;
    const K: usize = 8;
    let table = Arc::new(Mutex::new(FilterTable::new()));
    let mut handles = Vec::new();
    for t in 0..T {
        let table = Arc::clone(&table);
        handles.push(thread::spawn(move || {
            let mut ids = Vec::with_capacity(K);
            for k in 0..K {
                let id = table.lock().unwrap().add_filter(
                    0,
                    (100 + t * K + k) as u16,
                    0,
                    Some(Box::new(|_, _| {})),
                );
                if let Some(id) = id {
                    ids.push(id);
                }
            }
            for &id in &ids {
                table.lock().unwrap().del_filter(id);
            }
            ids
        }));
    }
    let mut fids = Vec::new();
    for handle in handles {
        fids.extend(handle.join().unwrap());
    }
    assert_eq!(fids.len(), T * K, "all filters added");
    let table = table.lock().unwrap();
    for id in fids {
        let filter = table.get(id);
        assert!(
            filter.is_some_and(|filter| !filter.enabled() && !filter.allocated()),
            "filter reclaimed after del"
        );
    }
}
